func TestTheAcknowledgementHeaderStaysOnScreenInsideItsCode(t *testing.T) {
	var lines []daemon.LineWire
	for n := 1; n <= 60; n++ {
		lines = append(lines, daemon.LineWire{Number: n, Text: fmt.Sprintf("generated %d", n), Side: "new", Changed: true})
	}
	step := ackStep()
	expansion := map[int][]daemon.ExcerptWire{0: {{File: "gen.go", Side: "new", FirstLine: 1, LastLine: 60, Lines: lines}}}
	cur := newStepCursor(step, expansion)
	cur.cursor = len(cur.lines) - 1
	const height = 20

	out := renderStep(step, cur, map[string]bool{}, nil, 80, height, false)

	if got := lipgloss.Height(out); got > height {
		t.Errorf("the pane is %d rows, over the %d given", got, height)
	}
	sticky := strings.Index(out, "Acknowledged")
	file := strings.Index(out, "── gen.go")
	code := strings.Index(out, "generated 60")
	if sticky < 0 || file < 0 || code < 0 {
		t.Fatalf("expected the Acknowledgement and file headers above the code:\n%s", out)
	}
	if !(sticky < file && file < code) {
		t.Errorf("expected the Acknowledgement header above the file header above the code:\n%s", out)
	}
	if !strings.Contains(out, "more above") {
		t.Error("expected a 'more above' indicator deep inside the expansion")
	}
}

