func TestAckChangeRequestsCountsThoseRaisedInEachAcknowledgement(t *testing.T) {
	first := 0
	m := model{view: &daemon.ViewWire{Posted: true, Position: 1, Step: ackStep(), ChangeRequests: []daemon.ChangeRequestWire{
		{Step: 1, File: "gen.go", Acknowledgement: &first},
		{Step: 1, File: "gen.go"}, // the same file, but in the Step's own code
		{Step: 2, File: "gen.go", Acknowledgement: &first},
	}}}

	counts := m.ackChangeRequests()

	if len(counts) != 1 || counts[0] != 1 {
		t.Errorf("expected one Change Request raised in this Step's Acknowledgement, got %v", counts)
	}
}

// expandServer answers /expand with ackExpansion, counting the calls.
func expandServer(t *testing.T) *httptest.Server {
	t.Helper()
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if !strings.HasPrefix(r.URL.Path, "/expand/") {
			http.NotFound(w, r)
			return
		}
		json.NewEncoder(w).Encode(ackExpansion())
	}))
	t.Cleanup(server.Close)
	return server
}

func stepModel(t *testing.T, step *daemon.StepWire) model {
	t.Helper()
	m := model{
		client: client{base: expandServer(t).URL},
		mode:   modeReview,
		view:   &daemon.ViewWire{Posted: true, Position: 1, StepCount: 1, Step: step},
		width:  80, height: 40, ready: true,
	}
	m.syncCursor()
	return m
}

func press(m model, key string) model {
	var msg tea.KeyMsg
	switch key {
	case "down":
		msg = tea.KeyMsg{Type: tea.KeyDown}
	case "up":
		msg = tea.KeyMsg{Type: tea.KeyUp}
	default:
		msg = tea.KeyMsg{Type: tea.KeyRunes, Runes: []rune(key)}
	}
	after, _ := m.Update(msg)
	return after.(model)
}

func TestXOnAStopExpandsItAndLandsInItsCode(t *testing.T) {
	m := press(stepModel(t, ackStep()), "down") // onto the stop

	m = press(m, "x")

	line := m.cursor.lines[m.cursor.cursor]
	if line.kind != kindCode || line.ack != 0 || line.number != 2 || line.side != "old" {
		t.Errorf("expected the cursor on the first row of the expansion, got %+v", line)
	}
}

func TestXInsideAcknowledgedCodeCollapsesItOntoItsStop(t *testing.T) {
	m := press(press(stepModel(t, ackStep()), "down"), "x")
	m = press(m, "down")

	m = press(m, "x")

	line := m.cursor.lines[m.cursor.cursor]
	if line.kind != kindStop || line.ack != 0 {
		t.Errorf("expected the cursor back on the stop, got %+v", line)
	}
	if len(m.cursor.lines) != 2 {
		t.Errorf("expected the expansion gone, got %d lines", len(m.cursor.lines))
	}
}

func TestSelectingOnAStopExplainsHowToReachTheCode(t *testing.T) {
	m := press(stepModel(t, ackStep()), "down")

	m = press(m, "v")

	if !strings.Contains(m.status, "expand with x") {
		t.Errorf("expected a hint to expand first, got %q", m.status)
	}
}

func TestAnEntirelyOpaqueAcknowledgementKeepsTheCursorOnItsStop(t *testing.T) {
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		json.NewEncoder(w).Encode([]daemon.ExcerptWire{{File: "logo.png", Problem: "logo.png is an Opaque Change (binary file) with no lines to show"}})
	}))
	defer server.Close()
	step := ackStep()
	step.Excerpts = nil
	m := stepModel(t, step)
	m.client = client{base: server.URL}

	m = press(m, "x")

	if line := m.cursor.lines[m.cursor.cursor]; line.kind != kindStop {
		t.Errorf("expected the cursor to stay on the stop, got %+v", line)
	}
	if !m.cursor.isExpanded(0) {
		t.Error("expected the Acknowledgement to be expanded")
	}
}
