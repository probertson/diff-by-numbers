func TestCoverageCountsOpaqueAndAcknowledgedChanges(t *testing.T) {
	walkthrough := validWalkthrough()
	walkthrough.Steps = []review.Step{
		{
			Name: "The code", Explanation: "the real change",
			Excerpts: []review.Excerpt{{Repository: "/repos/argus-portal", File: "a.ts", Side: review.NewSide, FirstLine: 1, LastLine: 10}},
		},
		acknowledgingStep("package-lock.json", "logo.png"),
	}
	lines := append(changed("a.ts", 1, 3), changed("package-lock.json", 1, 4)...) // 3 code + 4 lockfile
	opaque := []review.OpaqueChange{{File: "logo.png", Kind: review.OpaqueBinary}}
	session := sessionDerivingBoth(lines, opaque)
	mustPost(t, session, walkthrough)

	if got := session.View().Coverage.Total; got != 8 {
		t.Fatalf("expected total 8 (3 code + 4 lockfile + 1 binary), got %d", got)
	}

	mustAdvance(t, session)
	if got := session.View().Coverage.Seen; got != 3 {
		t.Errorf("after the code Step expected 3 seen, got %d", got)
	}

	mustAdvance(t, session)
	if got := session.View().Coverage.Seen; got != 8 {
		t.Errorf("after the acknowledgement Step expected all 8 seen, got %d", got)
	}
}

func TestAnAcknowledgementRendersAsAManifestOfFilesAndCounts(t *testing.T) {
	walkthrough := validWalkthrough()
	walkthrough.Steps = []review.Step{acknowledgingStep("package-lock.json", "logo.png")}
	lines := changed("package-lock.json", 1, 40)
	opaque := []review.OpaqueChange{{File: "logo.png", Kind: review.OpaqueBinary, Detail: "binary file"}}
	session := sessionDerivingBoth(lines, opaque)
	mustPost(t, session, walkthrough)
	mustAdvance(t, session)

	step := session.View().Step
	if step == nil || len(step.Acknowledgements) != 1 {
		t.Fatalf("expected one Acknowledgement in the Step view, got %+v", step)
	}
	ack := step.Acknowledgements[0]
	if ack.Reason == "" {
		t.Error("expected the manifest to carry the Acknowledgement's reason")
	}

	lock, ok := ackEntry(ack, "package-lock.json")
	if !ok || lock.ChangedLines != 40 {
		t.Errorf("expected package-lock.json with 40 changed lines, got %+v (found=%v)", lock, ok)
	}
	logo, ok := ackEntry(ack, "logo.png")
	if !ok || logo.Opaque != review.OpaqueBinary {
		t.Errorf("expected logo.png as a binary Opaque Change, got %+v (found=%v)", logo, ok)
	}
}

func TestManifestClassifiesWhatChangedPerFile(t *testing.T) {
	walkthrough := validWalkthrough()
	walkthrough.Steps = []review.Step{acknowledgingStep("mod.ts", "new.ts", "gone.ts", "logo.png")}
	lines := []review.ChangedLine{
		{File: "mod.ts", Side: review.OldSide, Line: 1},
		{File: "mod.ts", Side: review.NewSide, Line: 1},
		{File: "new.ts", Side: review.NewSide, Line: 1},
		{File: "new.ts", Side: review.NewSide, Line: 2},
		{File: "gone.ts", Side: review.OldSide, Line: 1},
		{File: "gone.ts", Side: review.OldSide, Line: 2},
	}
	opaque := []review.OpaqueChange{{File: "logo.png", Kind: review.OpaqueBinary}}
	session := sessionDerivingBoth(lines, opaque)
	mustPost(t, session, walkthrough)
	mustAdvance(t, session)

	ack := session.View().Step.Acknowledgements[0]
	want := map[string]string{
		"mod.ts":   review.ChangeModified,
		"new.ts":   review.ChangeAdded,
		"gone.ts":  review.ChangeRemoved,
		"logo.png": string(review.OpaqueBinary),
	}
	for file, expected := range want {
		entry, ok := ackEntry(ack, file)
		if !ok || entry.Change != expected {
			t.Errorf("expected %s classified as %q, got %q (found=%v)", file, expected, entry.Change, ok)
		}
	}
}

func TestAnAcknowledgementExpandsIntoRealExcerpts(t *testing.T) {
	walkthrough := validWalkthrough()
	walkthrough.Steps = []review.Step{acknowledgingStep("package-lock.json")}
	session := sessionDerivingBoth(changed("package-lock.json", 5, 9), nil)
	mustPost(t, session, walkthrough)

	views, err := session.ExpandAcknowledgement(1, 0)

	if err != nil {
		t.Fatalf("expected expansion to succeed, got %v", err)
	}
	var shownChanged []int
	for _, view := range views {
		for _, line := range view.Lines {
			if line.Changed {
				shownChanged = append(shownChanged, line.Number)
			}
		}
	}
	for _, n := range []int{5, 6, 7, 8, 9} {
		if !containsInt(shownChanged, n) {
			t.Errorf("expected the expansion to show changed line %d, got %v", n, shownChanged)
		}
	}
}

