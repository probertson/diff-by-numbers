func sessionDerivingBoth(lines []review.ChangedLine, opaque []review.OpaqueChange) *review.Session {
	return review.NewSession(stubResolver{}, fixedDeriver{lines: lines, opaque: opaque})
}

func acknowledgingStep(files ...string) review.Step {
	return review.Step{
		Name:        "Mechanical",
		Explanation: "regenerated and swapped, nothing to read line by line",
		Acknowledgements: []review.Acknowledgement{
			{Repository: "/repos/argus-portal", Files: files, Reason: "mechanical: regenerated by the build"},
		},
	}
}

func ackEntry(view review.AcknowledgementView, file string) (review.AcknowledgedFile, bool) {
	for _, entry := range view.Entries {
		if entry.File == file {
			return entry, true
		}
	}
	return review.AcknowledgedFile{}, false
}

func containsInt(haystack []int, needle int) bool {
	for _, n := range haystack {
		if n == needle {
			return true
		}
	}
	return false
}

