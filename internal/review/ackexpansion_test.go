// viewRow is one rendered row of an Excerpt's view, reduced to what a unified
// diff is judged by: which side it is on, its number, and whether it changed;
// and, in a Document, whether it was widened in.
type viewRow struct {
	side    review.Side
	number  int
	changed bool
	widened bool
}

func rowsOf(view review.ExcerptView) []viewRow {
	rows := make([]viewRow, len(view.Lines))
	for i, line := range view.Lines {
		rows[i] = viewRow{line.Side, line.Number, line.Changed, line.Widened}
	}
	return rows
}

func assertRows(t *testing.T, got, want []viewRow) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("expected %d rows %+v, got %d %+v", len(want), want, len(got), got)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("row %d: expected %+v, got %+v", i, want[i], got[i])
		}
	}
}

// acknowledgedEdits is a session whose one Step acknowledges mod.ts, which git saw
// as two edits: old line 2 replaced by new lines 2-3, then old lines 9-10 removed
// outright.
func acknowledgedEdits(t *testing.T) *review.Session {
	t.Helper()
	deriver := pairingDeriver{
		lines: []review.ChangedLine{
			{File: "mod.ts", Side: review.OldSide, Line: 2},
			{File: "mod.ts", Side: review.NewSide, Line: 2},
			{File: "mod.ts", Side: review.NewSide, Line: 3},
			{File: "mod.ts", Side: review.OldSide, Line: 9},
			{File: "mod.ts", Side: review.OldSide, Line: 10},
		},
		correspondences: []review.Correspondence{
			{File: "mod.ts", OldFirst: 2, OldLast: 2, NewFirst: 2, NewLast: 3},
			{File: "mod.ts", OldFirst: 9, OldLast: 10},
		},
	}
	session := review.NewSession(sideResolver{}, deriver)
	walkthrough := validRound()
	walkthrough.Steps = []review.Step{acknowledgingStep("mod.ts")}
	mustPost(t, session, walkthrough)
	mustAdvance(t, session)
	return session
}

func TestAnExpandedEditReadsAsAUnifiedDiff(t *testing.T) {
	session := acknowledgedEdits(t)

	views, err := session.ExpandAcknowledgement(1, 0)

	if err != nil {
		t.Fatalf("expected expansion to succeed, got %v", err)
	}
	if len(views) != 2 {
		t.Fatalf("expected one Excerpt per edit, got %d: %+v", len(views), views)
	}
	assertRows(t, rowsOf(views[0]), []viewRow{
		{review.OldSide, 2, true, false}, // the before it replaced, just above
		{review.NewSide, 2, true, false},
		{review.NewSide, 3, true, false},
	})
	// A pure removal has no after-side to sit beside, so it stays before-only — in
	// file order, after the edit above it.
	assertRows(t, rowsOf(views[1]), []viewRow{
		{review.OldSide, 9, true, false},
		{review.OldSide, 10, true, false},
	})
}

func TestAnAnchorCanPointIntoAcknowledgedCode(t *testing.T) {
	session := acknowledgedEdits(t)
	ack := 0
	target := review.AnchorTarget{
		Acknowledgement: &ack,
		ExcerptIndex:    0,
		Start:           oldRow(2),
		End:             newRow(3),
	}

	anchor, err := session.Anchor(target)

	if err != nil {
		t.Fatalf("expected an Anchor into acknowledged code, got %v", err)
	}
	if anchor.File != "mod.ts" || len(anchor.Lines) != 3 {
		t.Fatalf("expected the 3 rows of mod.ts's first edit, got %s with %d lines", anchor.File, len(anchor.Lines))
	}
	rendered := anchor.Render()
	// The Anchor must tell the agent it is disputing a "mechanical" claim, not
	// just pointing at a line.
	want := `acknowledged in Step "Mechanical" (mechanical: regenerated by the build)`
	if !strings.Contains(rendered, want) {
		t.Errorf("expected the rendered Anchor to contain %q\n---\n%s", want, rendered)
	}
}

func TestAnAnchorIntoNarratedCodeDoesNotClaimAnAcknowledgement(t *testing.T) {
	session := newSession()
	mustPost(t, session, validRound())
	mustAdvance(t, session)

	anchor, err := session.Anchor(span(0, 20, 22))

	if err != nil {
		t.Fatalf("expected an Anchor, got %v", err)
	}
	if strings.Contains(anchor.Render(), "acknowledged") {
		t.Errorf("expected narrated code not to read as acknowledged:\n%s", anchor.Render())
	}
}

func TestAnchoringAnAcknowledgementTheStepLacksIsRejected(t *testing.T) {
	session := acknowledgedEdits(t)
	ack := 4

	_, err := session.Anchor(review.AnchorTarget{Acknowledgement: &ack, Start: newRow(2), End: newRow(2)})

	assertRejected(t, err, review.RejectedBadSelection)
}

func TestAnchoringAnAcknowledgedOpaqueChangeIsRejected(t *testing.T) {
	walkthrough := validRound()
	walkthrough.Steps = []review.Step{acknowledgingStep("logo.png")}
	session := sessionDerivingBoth(nil, []review.OpaqueChange{{File: "logo.png", Kind: review.OpaqueBinary, Detail: "binary file"}})
	mustPost(t, session, walkthrough)
	mustAdvance(t, session)
	ack := 0

	_, err := session.Anchor(review.AnchorTarget{Acknowledgement: &ack, Start: newRow(1), End: newRow(1)})

	assertRejected(t, err, review.RejectedBadSelection)
}

func TestAnAnchorRemembersWhichAcknowledgementItLiesIn(t *testing.T) {
	session := acknowledgedEdits(t)
	ack := 0

	anchor, err := session.Anchor(review.AnchorTarget{Acknowledgement: &ack, Start: newRow(2), End: newRow(3)})

	if err != nil {
		t.Fatal(err)
	}
	if anchor.Acknowledgement == nil || *anchor.Acknowledgement != 0 {
		t.Errorf("expected the Anchor to record Acknowledgement 0, got %v", anchor.Acknowledgement)
	}
}

// acknowledgedDocumentAndCode is a session whose one Step acknowledges an edit to
// a Markdown Document beside an edit to code: in the Document a word of one
// paragraph is replaced and, further down, the last paragraph is removed
// outright; in the code one line is replaced.
func acknowledgedDocumentAndCode(t *testing.T) *review.Session {
	t.Helper()
	files := workingFiles{
		before: map[string]string{
			"docs/retries.md": markdown("# Retries", "A request is retried when the transport fails.", "## Limits", "Old limits applied\nonce a day."),
			"retry.go":        "func retry() {\n\tattempt()\n}\n",
		},
		after: map[string]string{
			"docs/retries.md": markdown("# Retries", "A request is resent when the transport fails.", "## Limits"),
			"retry.go":        "func retry() {\n\tresend()\n}\n",
		},
	}
	return openDocumentRound(t, files, review.Step{
		Name:        "Notes and their code",
		Explanation: "the agent's notes and the call they describe, read elsewhere",
		Acknowledgements: []review.Acknowledgement{{
			Repository: docsRepo, Files: []string{"docs/retries.md", "retry.go"}, Reason: "read in the design review",
		}},
	})
}

// expandedFile is what an Acknowledgement's expansion shows of one file.
func expandedFile(views []review.ExcerptView, file string) []review.ExcerptView {
	var out []review.ExcerptView
	for _, view := range views {
		if view.Excerpt.File == file {
			out = append(out, view)
		}
	}
	return out
}

func TestAnExpandedAcknowledgementOverAnEditedDocumentReadsAsTrackChanges(t *testing.T) {
	session := acknowledgedDocumentAndCode(t)

	views, err := session.ExpandAcknowledgement(1, 0)

	if err != nil {
		t.Fatalf("expected the Acknowledgement to expand, got %v", err)
	}
	document := expandedFile(views, "docs/retries.md")
	if len(document) != 2 {
		t.Fatalf("expected the Document's edit and its removal, got %d: %+v", len(document), document)
	}
	edited := []review.Block{{Kind: review.BlockParagraph, Side: review.NewSide,
		Lines: review.LineRange{First: 3, Last: 3}, Treatment: review.TreatmentEdited, Path: []string{"Retries"}}}
	if !reflect.DeepEqual(document[0].Blocks, edited) {
		t.Errorf("expected the paragraph edited\n%+v\ngot\n%+v", edited, document[0].Blocks)
	}
	runs := []review.WordRun{kept("A request is "), struck("retried"), inserted("resent"), kept(" when the transport fails.")}
	if got := trackedRuns(document[0], 1); !slices.Equal(got, runs) {
		t.Errorf("expected the merged flow\n%+v\ngot\n%+v", runs, got)
	}
	removed := []review.Block{{Kind: review.BlockParagraph, Side: review.OldSide,
		Lines: review.LineRange{First: 7, Last: 8}, Treatment: review.TreatmentRemoved,
		Path: []string{"Retries", "Limits"}}}
	if !reflect.DeepEqual(document[1].Blocks, removed) {
		t.Errorf("expected the dropped paragraph removed\n%+v\ngot\n%+v", removed, document[1].Blocks)
	}
}

func TestAParagraphEditedInTwoPlacesExpandsOnceWithBothEdits(t *testing.T) {
	// git sees two edits, a line apart, in one paragraph. Each alone would be
	// widened to the whole paragraph, so read apart they would show it twice.
	files := modifying("docs/retries.md",
		markdown("# Retries", "A request is retried\nwhen the transport\nfails badly."),
		markdown("# Retries", "A request is resent\nwhen the transport\nfails often."),
	)
	session := openDocumentRound(t, files, review.Step{
		Name:        "Notes",
		Explanation: "the agent's notes, read elsewhere",
		Acknowledgements: []review.Acknowledgement{{
			Repository: docsRepo, Files: []string{"docs/retries.md"}, Reason: "read in the design review",
		}},
	})

	views, err := session.ExpandAcknowledgement(1, 0)

	if err != nil {
		t.Fatalf("expected the Acknowledgement to expand, got %v", err)
	}
	if len(views) != 1 {
		t.Fatalf("expected the paragraph once, got %d Excerpts: %+v", len(views), views)
	}
	runs := []review.WordRun{
		kept("A request is "), struck("retried"), inserted("resent"),
		kept("when the transport"),
		kept("fails "), struck("badly."), inserted("often."),
	}
	if got := trackedRuns(views[0], 1); !slices.Equal(got, runs) {
		t.Errorf("expected both edits in the one paragraph\n%+v\ngot\n%+v", runs, got)
	}
}

func TestCodeInTheSameAcknowledgementAsADocumentStillExpandsAsAUnifiedDiff(t *testing.T) {
	session := acknowledgedDocumentAndCode(t)

	views, err := session.ExpandAcknowledgement(1, 0)

	if err != nil {
		t.Fatalf("expected the Acknowledgement to expand, got %v", err)
	}
	code := expandedFile(views, "retry.go")
	if len(code) != 1 {
		t.Fatalf("expected the code's one edit, got %d: %+v", len(code), code)
	}
	if blocks := code[0].Blocks; len(blocks) != 0 {
		t.Errorf("expected code to carry no blocks, got %+v", blocks)
	}
	assertRows(t, rowsOf(code[0]), []viewRow{
		{review.OldSide, 2, true, false},
		{review.NewSide, 2, true, false},
	})
}
